class WindowTrimmingTests(unittest.TestCase):
    """Direct cover for the two helpers the parsing correctness rests on."""

    def _bgcode(self, text: str) -> bytes:
        """A real .bgcode built by pybgcode itself from ascii G-code."""
        import importlib.util as _importlib

        assert _importlib.find_spec("pybgcode") is not None, "pybgcode required for this test"
        import pybgcode

        with tempfile.TemporaryDirectory() as scratch:
            scratch_path = Path(scratch)
            ascii_path = scratch_path / "source.gcode"
            binary_path = scratch_path / "print.bgcode"
            # The converter requires the slicer-config section, as real files carry.
            full = text + "; prusaslicer_config = begin\nlayer_height = 0.2\n; prusaslicer_config = end\n"
            ascii_path.write_text(full, encoding="utf-8")
            source = pybgcode.open(str(ascii_path), "r")
            target = pybgcode.open(str(binary_path), "w")
            try:
                result = pybgcode.from_ascii_to_binary(source, target)
            finally:
                pybgcode.close(source)
                pybgcode.close(target)
            assert result == pybgcode.EResult.Success, result
            return binary_path.read_bytes()

    def test_binary_default_output_is_decoded_through_the_bgcode_reader(self) -> None:
        # The slicer's native binary output is a container whose decoded text
        # feeds the same summary parsing; this is the U1 wiring pin.
        runner = _Runner(gcode=None)
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            project = _project(root)
            binary = root / "PrusaSlicer"
            binary.write_text("", encoding="utf-8")

            def write_binary(command, **kwargs):
                result = runner(command, **kwargs)
                Path(command[command.index("--output") + 1]).write_bytes(self._bgcode(GCODE))
                return result

            result = slice_project(
                project, PRESETS, bindings=_bindings(project), executable=binary, runner=write_binary
            )
        self.assertTrue(result["ok"], result)
        self.assertNotIn("--binary-gcode=0", result["command"])
        self.assertEqual(3.93, result["statistics"]["total_filament_used_g"])
        self.assertEqual("18m 4s", result["statistics"]["estimated_printing_time_normal"])

    def test_corrupt_binary_output_is_a_structured_failure(self) -> None:
        runner = _Runner(gcode="GCDE\x01 not really a container")
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            project = _project(root)
            binary = root / "PrusaSlicer"
            binary.write_text("", encoding="utf-8")
            result = slice_project(
                project, PRESETS, bindings=_bindings(project), executable=binary, runner=runner
            )
            self.assertFalse((root / "project.gcode").exists())
        self.assertFalse(result["ok"])
        self.assertIn("Binary G-code container is unreadable", result["failure"])
        self.assertNotIn("statistics", result)

    def test_partial_lines_at_a_window_boundary_are_discarded(self) -> None:
        window = b"used [g] = 41.9\n; next = 1\n; trailing partial = 4"
        self.assertEqual(
            b"; next = 1\n; trailing partial = 4",
            prusaslicer_slice._whole_lines(window, drop_leading=True, drop_trailing=False),
        )
        self.assertEqual(
            b"used [g] = 41.9\n; next = 1\n",
            prusaslicer_slice._whole_lines(window, drop_leading=False, drop_trailing=True),
        )
        # A window holding no complete line yields nothing rather than a fragment.
        self.assertEqual(
            b"", prusaslicer_slice._whole_lines(b"g] = 41.9", drop_leading=True, drop_trailing=False)
        )
        self.assertEqual(
            b"", prusaslicer_slice._whole_lines(b"g] = 41.9", drop_leading=False, drop_trailing=True)
        )
        self.assertEqual(
            window, prusaslicer_slice._whole_lines(window, drop_leading=False, drop_trailing=False)
        )

    def test_the_summary_block_is_the_trailing_comment_run_only(self) -> None:
        self.assertEqual(
            ["; a = 1", "; b = 2"],
            prusaslicer_slice.summary_block("; spoof = 9\nG1 X1\n; a = 1\n; b = 2\n"),
        )
        # Stops at the config marker, and at the last non-comment line before it.
        self.assertEqual(
            ["; a = 1"],
            prusaslicer_slice.summary_block(
                "; a = 1\n; prusaslicer_config = begin\n; a = 9\n; prusaslicer_config = end\n"
            ),
        )
        self.assertEqual([], prusaslicer_slice.summary_block("; spoof = 9\nG1 X1\nM84\n"))
        self.assertEqual([], prusaslicer_slice.summary_block(""))


