def _project(root: Path) -> Path:
    path = root / "project.3mf"
    path.write_bytes(b"PK\x03\x04 pretend project")
    return path


def _bindings(project: Path, **extra) -> dict:
    """The chain a real caller passes: the project hash plus what produced it."""
    return {
        "project_sha256": hashlib.sha256(project.read_bytes()).hexdigest(),
        "manifest_sha256": "b" * 64,
        "export_index_sha256": "c" * 64,
        "verification_report_sha256": "d" * 64,
        "export_run_id": "0123456789abcdef0123456789abcdef",
        **extra,
    }


class IncompleteProfileSetTests(unittest.TestCase):
    """The actual defect: a partial profile set is what segfaults PrusaSlicer."""

    def test_each_missing_kind_is_refused_by_name(self) -> None:
        complete = {"printer": "P", "print": "Q", "filament": "M"}
        for kind in ("printer", "print", "filament"):
            for empty in (None, "", "   "):
                with self.subTest(kind=kind, empty=empty):
                    partial = {**complete, kind: empty}
                    with self.assertRaises(IncompleteProfileSetError) as caught:
                        require_complete_profile_set(partial)
                    self.assertIn(kind, str(caught.exception))
                    self.assertIn("139", str(caught.exception))

    def test_complete_set_is_returned_stripped(self) -> None:
        self.assertEqual(
            {"printer": "P", "print": "Q", "filament": "M"},
            require_complete_profile_set({"printer": " P ", "print": "Q", "filament": "M"}),
        )

    def test_resolved_presets_are_accepted(self) -> None:
        self.assertEqual(
            {
                "printer": PRESETS.printer,
                "print": PRESETS.print_settings,
                "filament": PRESETS.filament,
            },
            require_complete_profile_set(PRESETS),
        )

    def test_nothing_is_executed_when_the_set_is_incomplete(self) -> None:
        runner = _Runner()
        with tempfile.TemporaryDirectory() as temporary:
            project = _project(Path(temporary))
            with self.assertRaises(IncompleteProfileSetError):
                slice_project(
                    project,
                    {"printer": "P", "print": "Q"},
                    bindings=_bindings(project),
                    executable=project,  # any existing file; must never be reached
                    runner=runner,
                )
        self.assertEqual([], runner.calls)


