#!/usr/bin/env node
// PreToolUse gate on the Fusion MCP execute tool. Two mechanically checkable
// rules from the fusion-parametric-design doctrine, enforced as mechanism:
//
// 1. Process-spawning constructs are always blocked. Inside Fusion,
//    sys.executable is the Fusion binary, so subprocess/os.system/os.exec*/
//    ensurepip/multiprocessing/Popen spawn a second Fusion instance — a
//    measured incident, and the shipped tooling's own test suite asserts no
//    emitted transaction starts a process. No exemption.
// 2. Ad hoc script payloads over the size threshold are blocked unless they
//    carry the shipped tooling's signature. Generated lane transactions
//    legitimately run long and always carry the report-protocol prelude
//    (FUSION_DESIGN_REPORT_BEGIN) or the bootstrap header; an ad hoc monolith
//    is exactly what the thin-transport rule prohibits.
//
// Fail-open discipline: anything this gate cannot parse or recognize is
// allowed with a DEGRADED note on stderr. The gate must never break a
// session on its own confusion.
//
// This is a mechanical nudge against accidental drift, not a security
// boundary. Doctrine (SKILL.md §1, the cumulative thin-scripting rule) is the
// cross-harness authority; deliberately forging a lane marker is already a
// doctrine violation, and the hook does not try to outrun it.

// Threshold rationale: a thin ordinary-lane snippet is one visible edit —
// measured shipped examples run well under 100 lines / 4 KB, while the
// incident's candidate monolith ran ~1,500 lines. 120 lines / 8 KB leaves
// generous headroom for one feature group plus its construction entities
// without admitting a product-builder.
const MAX_ADHOC_LINES = 120;
const MAX_ADHOC_BYTES = 8192;

// Always blocked, marker or not: these invoke a process when reached.
const SPAWN_PATTERNS = [
  [/\bsubprocess\b/, "subprocess"],
  [/\bmultiprocessing\b/, "multiprocessing"],
  [/\bos\s*\.\s*(system|popen|exec\w*|spawn\w*|posix_spawn\w*|fork\w*|startfile)\b/, "an os process API"],
  [/\bfrom\s+os\s+import\b[^\n]*\b(system|popen|exec\w*|spawn\w*|posix_spawn\w*|fork\w*|startfile)\b/, "an os process API import"],
  // Parenthesized import lists span lines; [^)]* crosses newlines.
  [/\bfrom\s+os\s+import\s*\([^)]*\b(system|popen|exec\w*|spawn\w*|posix_spawn\w*|fork\w*|startfile)\b[^)]*\)/, "an os process API import"],
  [/\bpty\b/, "pty"],
  // Aliasing os away from its name has no honest use in a thin snippet; the
  // aliased member calls it enables would otherwise slip the qualified-name
  // patterns. Deeper evasion (__import__, getattr chains, importlib) is
  // deliberate forging — the declared doctrine boundary, not a regex race.
  [/\bimport\s+os\s+as\b/, "an os alias import"],
  [/\b__import__\s*\(/, "__import__"],
  [/\bPopen\b/, "Popen"],
  [/\bposix_spawn\w*\s*\(/, "posix_spawn"],
  [/\bfork\s*\(/, "fork"],
];

// Blocked in ad hoc scripts only: the shipped capability probe imports
// `ensurepip` by name purely to report whether the module exists — an
// inspection, not an invocation — and that emitted script carries the lane
// marker. Ad hoc code has no reason to touch it.
const ADHOC_SPAWN_PATTERNS = [[/\bensurepip\b/, "ensurepip"]];

// The lane exemption matches the shipped emitters' actual output shape:
// every generated transaction's prelude declares the report constant on its
// own line near the top, and the module bootstrap opens with its header
// comment. Line-anchored and confined to the leading portion, so a marker
// buried in a string mid-script exempts nothing.
const LANE_MARKER_WINDOW = 4096;
const LANE_MARKERS = [
  /^REPORT_BEGIN = ['"]FUSION_DESIGN_REPORT_BEGIN['"]\s*$/m,
  /^# Generated by fusion-design/m,
];

// Blank out `#` comments and quoted-string contents (single/double/triple,
// backslash-escape tolerant) so the spawn patterns see only code-position
// tokens — a manifest project named "subprocess fixture" is data, not a
// spawn. A lightweight state machine, not a parser: stripped characters
// become spaces, delimiters stay. The size gate and the lane-marker check
// still read the RAW script (the marker itself lives in a string literal).
function stripPython(script) {
  const out = [];
  let mode = ""; // "", "'", '"', "'''", '"""', "#"
  let fstring = false; // the current string literal has an f prefix
  let braceDepth = 0; // >0: inside an f-string {expression} — executable, preserved
  let i = 0;
  while (i < script.length) {
    const ch = script[i];
    if (mode === "#") {
      if (ch === "\n") {
        mode = "";
        out.push(ch);
      } else out.push(" ");
      i += 1;
    } else if (mode === "") {
      const triple = script.slice(i, i + 3);
      if (triple === "'''" || triple === '"""') {
        mode = triple;
        fstring = /[fF]/.test((script.slice(0, i).match(/[A-Za-z]*$/) || [""])[0]);
        out.push(triple);
        i += 3;
      } else if (ch === "'" || ch === '"') {
        mode = ch;
        fstring = /[fF]/.test((script.slice(0, i).match(/[A-Za-z]*$/) || [""])[0]);
        out.push(ch);
        i += 1;
      } else if (ch === "#") {
        mode = "#";
        out.push(" ");
        i += 1;
      } else {
        out.push(ch);
        i += 1;
      }
    } else if (braceDepth > 0) {
      // f-string interpolation expression: executable code, preserved verbatim.
      // ponytail: a nested string containing braces can miscount the depth;
      // the failure direction is under-stripping, which only over-blocks.
      if (ch === "{") braceDepth += 1;
      else if (ch === "}") braceDepth -= 1;
      out.push(ch);
      i += 1;
    } else {
      // inside a string: escapes skip the next character
      if (ch === "\\") {
        out.push("  ");
        i += 2;
      } else if (fstring && ch === "{" && script[i + 1] === "{") {
        out.push("  ");
        i += 2;
      } else if (fstring && ch === "}" && script[i + 1] === "}") {
        out.push("  ");
        i += 2;
      } else if (fstring && ch === "{") {
        braceDepth = 1;
        out.push(ch);
        i += 1;
      } else if (mode.length === 3 && script.slice(i, i + 3) === mode) {
        out.push(mode);
        mode = "";
        fstring = false;
        i += 3;
      } else if (mode.length === 1 && ch === mode) {
        out.push(ch);
        mode = "";
        fstring = false;
        i += 1;
      } else {
        out.push(ch === "\n" ? "\n" : " ");
        i += 1;
      }
    }
  }
  return out.join("");
}

function degrade(reason) {
  process.stderr.write(`[fusion-script-gate] DEGRADED: ${reason}; allowing.\n`);
  process.exit(0);
}

function block(message) {
  process.stderr.write(`[fusion-script-gate] Blocked: ${message}\n`);
  process.exit(2);
}

function extractScript(input) {
  const toolInput = input && input.tool_input;
  if (!toolInput || typeof toolInput !== "object") return undefined;
  if (typeof toolInput.script === "string") return toolInput.script;
  const object = toolInput.object;
  if (object && typeof object === "object" && typeof object.script === "string") {
    return object.script;
  }
  return undefined;
}

function gate(raw) {
  let input;
  try {
    input = JSON.parse(raw);
  } catch {
    return degrade("hook input was not parseable JSON");
  }
  try {
    const toolName = typeof input.tool_name === "string" ? input.tool_name : "";
    // Only the Fusion execute surface carries a script payload worth gating.
    if (!/fusion/i.test(toolName) || !/execute/i.test(toolName)) process.exit(0);
    const script = extractScript(input);
    if (typeof script !== "string" || !script) process.exit(0);

    const leading = script.slice(0, LANE_MARKER_WINDOW);
    const laneMarked = LANE_MARKERS.some((marker) => marker.test(leading));
    const spawnPatterns = laneMarked
      ? SPAWN_PATTERNS
      : SPAWN_PATTERNS.concat(ADHOC_SPAWN_PATTERNS);
    // Scan stripped text so strings/comments never false-positive; on any
    // stripper trouble, scan the raw text (conservative) and say so.
    let scanText;
    try {
      if (process.env.FUSION_GATE_NO_STRIP) throw new Error("stripping disabled");
      scanText = stripPython(script);
      if (typeof scanText !== "string" || scanText.length === 0) {
        throw new Error("stripper returned nothing");
      }
    } catch (error) {
      process.stderr.write(
        `[fusion-script-gate] DEGRADED: comment/string stripping unavailable (${
          error && error.message
        }); scanning raw text.\n`,
      );
      scanText = script;
    }
    for (const [pattern, name] of spawnPatterns) {
      if (pattern.test(scanText)) {
        block(
          `the script contains ${name}. Inside Fusion, sys.executable is the ` +
            "Fusion binary, so spawning a process launches a second Fusion " +
            "instance (measured incident). Run host-side work in the host " +
            "environment and pass only results into Fusion; no Fusion script " +
            "may start a process.",
        );
      }
    }

    const bytes = Buffer.byteLength(script, "utf8");
    const lines = script.split("\n").length;
    if (bytes > MAX_ADHOC_BYTES || lines > MAX_ADHOC_LINES) {
      if (!laneMarked) {
        block(
          `ad hoc script is ${lines} lines / ${bytes} bytes, over the thin-` +
            `transport bound (${MAX_ADHOC_LINES} lines / ${MAX_ADHOC_BYTES} ` +
            "bytes). Thin means one visible edit, not one product goal " +
            "(SKILL.md §1): split into one visible edit per snippet, or run " +
            "the shipped lane tooling — generated transactions carry the " +
            "report-protocol marker and pass this gate unchanged.",
        );
      }
    }
    process.exit(0);
  } catch (error) {
    return degrade(`unexpected error (${error && error.message})`);
  }
}

let raw = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => {
  raw += chunk;
});
process.stdin.on("end", () => gate(raw));
